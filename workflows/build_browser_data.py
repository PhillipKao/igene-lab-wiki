#!/usr/bin/env python3
"""
Compile wiki/ Markdown pages and raw/registry.json into wiki_browser/wiki_data.js
so the local Warm Orange Wiki Browser works seamlessly both over file:// and http://localhost.
"""

from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WIKI_DIR = ROOT / "wiki"
RAW_DIR = ROOT / "raw"
BROWSER_DIR = ROOT / "wiki_browser"

CATEGORIES = [
    {"id": "products", "label": "檢測產品", "en": "Products", "desc": "PGT-A、ECS、PGT-SR、PGT-M 四大生殖遺傳檢測主頁"},
    {"id": "concepts", "label": "核心概念", "en": "Concepts", "desc": "生殖遺傳、染色體與分子檢測基礎知識條目"},
    {"id": "evidence", "label": "臨床證據", "en": "Evidence", "desc": "ASRM、ESHRE、ACMG 跨指引證據整合與爭議對照"},
    {"id": "laboratory", "label": "實驗室規範", "en": "Laboratory", "desc": "實驗室架構、PGT 作業流程、品質管理與檢體追溯"},
    {"id": "faq", "label": "常見問題", "en": "FAQ", "desc": "一般民眾與患者白話衛教問答"},
]


def parse_frontmatter(text: str) -> tuple[dict, str]:
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---\n", 4)
    if end == -1:
        return {}, text
    fm_raw = text[4:end]
    body = text[end + 5 :].lstrip("\n")
    data: dict = {}
    current_list_key: str | None = None
    for raw_line in fm_raw.splitlines():
        line = raw_line.rstrip()
        if not line or line.lstrip().startswith("#"):
            continue
        if line.startswith("  - ") or line.startswith("- "):
            if current_list_key is not None:
                val = line.split("- ", 1)[1].strip().strip('"').strip("'")
                data[current_list_key].append(val)
            continue
        if ":" in line:
            k, v = line.split(":", 1)
            k = k.strip()
            v = v.strip()
            if v == "":
                data[k] = []
                current_list_key = k
            else:
                data[k] = v.strip('"').strip("'")
                current_list_key = None
    return data, body


def main() -> int:
    BROWSER_DIR.mkdir(parents=True, exist_ok=True)
    registry = json.loads((RAW_DIR / "registry.json").read_text(encoding="utf-8"))
    sources = registry.get("sources", [])

    pages = []
    for cat in CATEGORIES:
        cat_dir = WIKI_DIR / cat["id"]
        if not cat_dir.exists():
            continue
        for md_path in sorted(cat_dir.glob("*.md")):
            rel_id = md_path.relative_to(WIKI_DIR).as_posix()  # e.g. products/pgt-a.md
            fm, body = parse_frontmatter(md_path.read_text(encoding="utf-8"))
            # Resolve related_pages relative to wiki/
            resolved_related = []
            for rp in fm.get("related_pages", []):
                target = (md_path.parent / rp).resolve()
                try:
                    resolved_related.append(target.relative_to(WIKI_DIR.resolve()).as_posix())
                except ValueError:
                    pass
            pages.append(
                {
                    "id": rel_id,
                    "slug": md_path.stem,
                    "category": fm.get("category", cat["id"]),
                    "title": fm.get("title", md_path.stem),
                    "summary": fm.get("summary", ""),
                    "source_ids": fm.get("source_ids", []),
                    "created_at": fm.get("created_at", ""),
                    "updated_at": fm.get("updated_at", ""),
                    "review_status": fm.get("review_status", "draft"),
                    "review_layers": fm.get("review_layers", []),
                    "related_pages": resolved_related,
                    "markdown": body,
                }
            )

    igene_json_path = RAW_DIR / "structured" / "igene_disease_list.json"
    igene_panel = json.loads(igene_json_path.read_text(encoding="utf-8")) if igene_json_path.exists() else None

    payload = {
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "categories": CATEGORIES,
        "pages": pages,
        "sources": sources,
        "igene_panel": igene_panel,
        "wiki_log": (WIKI_DIR / "log.md").read_text(encoding="utf-8") if (WIKI_DIR / "log.md").exists() else "",
    }

    out_path = BROWSER_DIR / "wiki_data.js"
    out_path.write_text(
        "// Auto-generated by workflows/build_browser_data.py — do not edit manually.\n"
        "window.WIKI_DATA = "
        + json.dumps(payload, ensure_ascii=False, indent=2)
        + ";\n",
        encoding="utf-8",
    )
    print(f"Built {out_path.relative_to(ROOT)} ({len(pages)} pages, {len(sources)} sources)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
