#!/usr/bin/env python3
"""
Build sanitized public reference dataset for the Classroom Teaching Demo Edition:
  raw/structured/igene_disease_list.json -> publish/ecs-demo/ecs_public_data.js

Safety transformations for public classroom deployment:
  - Preserves authentic SRC-009 disease names, gene symbols, inheritance patterns,
    reference populations, and public carrier frequencies (350 rows / 351 unique genes).
  - Explicitly strips `detection_rate` (`det`) so unverified product performance
    percentages are NOT shipped in the public demo payload.
  - Excludes internal workspace paths and unverified laboratory technical specs.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC_JSON = ROOT / "raw" / "structured" / "igene_disease_list.json"
OUT_DIR = ROOT / "publish" / "ecs-demo"
OUT_JS = OUT_DIR / "ecs_public_data.js"


def main() -> int:
    if not SRC_JSON.exists():
        print(f"ERROR: Missing {SRC_JSON}", file=sys.stderr)
        return 1

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    data = json.loads(SRC_JSON.read_text(encoding="utf-8"))

    # Intentionally omit `detection_rate` (unverified product performance metric)
    sanitized_items = [
        {
            "id": it["row_id"],
            "cat": it["primary_category"],
            "catFull": it["disease_category"],
            "zh": it["disease_name_zh"],
            "en": it["disease_name_en"],
            "gene": it["gene_symbol"],
            "inh": it["inheritance_pattern"],
            "pop": it["population"],
            "freq": it["carrier_frequency"],
        }
        for it in data.get("items", [])
    ]

    payload = {
        "edition": "classroom-teaching-demo",
        "disclaimer": "課程教學示範，非個人化醫療建議",
        "source_id": data.get("source_id", "SRC-009"),
        "source_label": "公開 ECS 疾病清單教學範例（SRC-009）",
        "source_url": data.get("source_url", "https://www.icryobank.com/gene/igene-disease-list"),
        "retrieved_date": data.get("retrieved_date", "2026-11-23"),
        "omitted_fields": ["detection_rate"],
        "summary_stats": {
            "extracted_disease_rows": data["summary_stats"]["extracted_disease_rows"],
            "unique_individual_gene_symbols": data["summary_stats"]["unique_individual_gene_symbols"],
            "extracted_primary_categories": data["summary_stats"]["extracted_primary_categories"],
            "x_linked_unique_genes_count": data["summary_stats"]["x_linked_unique_genes_count"],
            "inheritance_pattern_counts": data["summary_stats"]["inheritance_pattern_counts"],
            "primary_category_counts": data["summary_stats"]["primary_category_counts"],
        },
        "items": sanitized_items,
    }

    OUT_JS.write_text(
        "// Auto-generated by workflows/build_ecs_demo_data.py (Classroom Teaching Demo Edition)\n"
        "// Note: Product detection_rate values are intentionally omitted for public educational deployment.\n"
        "window.ECS_DEMO_DATA = "
        + json.dumps(payload, ensure_ascii=False)
        + ";\n",
        encoding="utf-8",
    )
    print(
        f"Built {OUT_JS.relative_to(ROOT)} "
        f"({len(sanitized_items)} items, unique_genes={payload['summary_stats']['unique_individual_gene_symbols']}, "
        f"omitted={payload['omitted_fields']})"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
